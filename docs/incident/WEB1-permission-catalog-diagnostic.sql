-- Missing canonical catalog rows (the repair candidate set).
SELECT e.Id AS ExpectedId, e.Name, e.Description
FROM ExpectedPermissions e
LEFT JOIN Permissions p ON p.Name = e.Name
WHERE p.Id IS NULL
ORDER BY e.Id;

-- Name exists but has a different ID: investigate before repair; do not renumber existing rows.
SELECT e.Id AS ExpectedId, e.Name, p.Id AS ExistingId
FROM ExpectedPermissions e
JOIN Permissions p ON p.Name = e.Name
WHERE p.Id <> e.Id
ORDER BY e.Id;

-- Expected ID is occupied by another permission name: investigate before repair.
SELECT e.Id AS ExpectedId, e.Name AS ExpectedName, p.Name AS ExistingName
FROM ExpectedPermissions e
JOIN Permissions p ON p.Id = e.Id
WHERE p.Name <> e.Name
ORDER BY e.Id;

-- Existing catalog rows absent from the current canonical registry (review only).
SELECT p.Id, p.Name, p.Description
FROM Permissions p
LEFT JOIN ExpectedPermissions e ON e.Name = p.Name
WHERE e.Name IS NULL
